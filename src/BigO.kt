// O(n) — «как быстро растёт работа», если данных становится больше; n — сколько элементов
// steps — шаги, pairs — пары, ++ — прибавь 1
// O(1): всегда 1 шаг (first()). O(n): шагов столько, сколько элементов. O(n²): n × n шагов.

fun main() {
    val nums = listOf(3, 8, 1, 10, 5)

    // 1. Один цикл — каждое число один раз: O(n)
    var steps = 0
    for (n in nums) {
        steps++
    }
    println(steps)    // 5   (10 чисел → 10, 1000 → 1000)

    // 2. Цикл внутри цикла — каждое число с каждым: O(n²)
    var pairs = 0
    for (a in nums) {
        for (b in nums) {
            pairs++
        }
    }
    println(pairs)    // 25  (10 чисел → 100, 1000 → 1 000 000)

    // 3. first() — не проходит по списку: O(1)
    println(nums.first())   // 3 — один шаг и для 5, и для 1000 чисел
}
