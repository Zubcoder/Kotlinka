// when — когда, else — все остальные, -> «если такое, то вот это»
// grade — оценка, temp (temperature) — температура, weather — погода
// type — тип, color — цвет

fun main() {
    val grade = 7
    val word = when (grade) {
        5 -> "отлично"
        4 -> "хорошо"
        3 -> "удовлетворительно"
        1, 2 -> "плохо"               // несколько значений через запятую
        else -> "нет такой оценки"
    }
    println(word)                     // нет такой оценки

    val temp = -3
    val weather = when {              // без скобок: в каждой строке своё условие
        temp < 0 -> "мороз"           // узкое условие — выше широкого
        temp < 15 -> "прохладно"
        else -> "тепло"
    }
    println(weather)                  // мороз

    // цвет кодпичика в «Кодёнке»
    val type = "цикл"
    val color = when (type) {
        "коробка" -> "жёлтый"
        "цикл" -> "бирюзовый"
        "условие" -> "оранжевый"
        "функция" -> "фиолетовый"
        else -> "серый"
    }
    println(color)                    // бирюзовый
}
